-- Починка диапазонов состава окон, которые оставила миграция 030.
--
-- Правкой самой 030 это сделать нельзя: `runBookMarkupMigrations` сверяет
-- контрольную сумму файла до выполнения SQL и роняет весь прогон миграций с
-- `applied migration checksum changed`. База, на которую 030 уже накатилась, от
-- такой правки просто перестала бы стартовать, и никакая идемпотентность внутри
-- файла тут не помогает. Поэтому исправление живёт отдельной миграцией.
--
-- Что чинить. Досчёт в 030 смещал диапазон на одно окно: окно N забирало
-- пролёт окна N−1. У первого окна предыдущего нет, `LAG` пуст, а `start_offset`
-- у всех окон равен нулю — и первое окно получало [0, 0], то есть не отвечало
-- ни за кого. Второе окно при этом забирало обе первые главы. Для читателя это
-- значит, что ранние герои теряли приоритет первого окна и получали барьер
-- карточки от чужого окна.
--
-- Чем чинить. Точный диапазон считается по границам глав, а из строк окон они
-- не восстанавливаются: у первого окна глав несколько, и внутренние границы в
-- базе не записаны. Поэтому окно забирает свой собственный пролёт — от конца
-- предыдущего окна до своего конца. Диапазоны выходят непересекающимися и
-- непустыми; барьер оказывается на главу уже точного, то есть «глава
-- появления» вместо «глава появления + 1» — беднее, но без спойлеров. Точные
-- диапазоны новый прогон получает от `buildBookCardWindows`, старому для этого
-- нужен повторный Prepare.
--
-- Кого чинить. Только прогоны с подписью дефекта: первое окно с диапазоном
-- [0, 0]. Настоящее первое окно либо владеет главами и кончается позже нуля,
-- либо не владеет ничем — и тогда `buildBookCardWindows` записывает ему
-- [end_offset, end_offset], где end_offset больше нуля. Так что [0, 0] у окна
-- ноль означает ровно старый досчёт, и прогоны с точными диапазонами не
-- трогаются.

WITH broken AS (
  SELECT run_id
  FROM book_card_windows
  WHERE window_index = 0
    AND assign_start_offset = 0
    AND assign_end_offset = 0
),
own_span AS (
  SELECT run_id, window_index,
         COALESCE(LAG(end_offset) OVER (PARTITION BY run_id ORDER BY window_index), 0)
           AS assign_start,
         end_offset AS assign_end
  FROM book_card_windows
  WHERE run_id IN (SELECT run_id FROM broken)
)
UPDATE book_card_windows AS target
SET assign_start_offset = own_span.assign_start,
    assign_end_offset = GREATEST(own_span.assign_end, own_span.assign_start)
FROM own_span
WHERE target.run_id = own_span.run_id
  AND target.window_index = own_span.window_index;
