-- Очередь заданий ищется по типу, а не перебором чужих.
--
-- Индекс очереди стоял на (priority, available_at, created_at) без типа
-- задания. Пока очередь однородна, это незаметно; но стоило поставить семь
-- тысяч озвучек, как двенадцать карточных воркеров начали каждую секунду
-- проходить по ним в порядке приоритета, чтобы не найти ни одной своей.
-- Postgres упёрся в два ядра из четырёх, хост ушёл в перезагрузку, а сама
-- озвучка шла 26 штук в минуту вместо ожидаемых ста.
--
-- Тип задания первым столбцом: каждый воркер попадает сразу в свою очередь.
-- После правки нагрузка упала с 22 до 4.5, скорость выросла до 59 в минуту.
--
-- Прежний индекс остаётся: по нему ходит операторская выборка «вся очередь по
-- приоритету», которой тип не важен.
CREATE INDEX IF NOT EXISTS generation_jobs_claim_by_type
  ON generation_jobs (job_type, priority DESC, available_at, created_at)
  WHERE status = 'queued';
