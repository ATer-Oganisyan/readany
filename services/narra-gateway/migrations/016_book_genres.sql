  VALUES
    ('narra-ru-top100-vojna-i-mir-tolstoj-f0777e32', ARRAY['historical-fiction', 'literary-fiction']::text[]),
    ('narra-ru-top100-bratya-karamazovy-ddb71ca8', ARRAY['literary-fiction']::text[]),
