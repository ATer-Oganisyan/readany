normalized_editions AS (
  SELECT
    edition.id,
    edition.catalog_key,
    edition.title,
    CASE
      WHEN edition.catalog_key ~ '^narra-(ru|en)-[0-9]+-' THEN
        regexp_replace(edition.catalog_key, '^narra-(ru|en)-[0-9]+-', '')
      WHEN edition.catalog_key ~ '^eval-v[0-9]+(-b[0-9]+)?-' THEN
        regexp_replace(edition.catalog_key, '^eval-v[0-9]+(-b[0-9]+)?-', '')
      ELSE edition.catalog_key
    END AS source_key,
    CASE
      WHEN edition.catalog_key ~ '^narra-en-' THEN 'en'
      WHEN edition.catalog_key ~ '^(narra-ru-|eval-)' THEN 'ru'
      ELSE NULL
    END AS inferred_language
  FROM book_editions AS edition
  WHERE edition.scope = 'catalog'
),
resolved_mapping AS (
  SELECT edition.id AS book_edition_id, mapping.genres
  FROM normalized_editions AS edition
  JOIN source_mapping AS mapping ON mapping.source_key = edition.source_key
  WHERE mapping.source_key <> 'faust'
     OR mapping.language = edition.inferred_language
     OR lower(mapping.title) = lower(edition.title)

  UNION ALL

  SELECT edition.id AS book_edition_id, alias.genres
  FROM normalized_editions AS edition
  JOIN catalog_key_aliases AS alias ON alias.catalog_key = edition.catalog_key
)
INSERT INTO book_edition_genres (book_edition_id, genre, position)
SELECT
  mapping.book_edition_id,
  genre.value,
  genre.ordinality::smallint
FROM resolved_mapping AS mapping
CROSS JOIN LATERAL unnest(mapping.genres) WITH ORDINALITY AS genre(value, ordinality)
ON CONFLICT (book_edition_id, genre) DO UPDATE
SET position = EXCLUDED.position;
