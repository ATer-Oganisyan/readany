/**
 * Словарь и морфология черт личности — русский язык первым.
 *
 * Модуль лежит в `analysis/`, а не в `generation/`: это словарь о тексте книги,
 * и им пользуются обе стороны — прогрессивная личность в анализе и аудит
 * карточки в генерации. Обратное направление зависимости завело бы цикл.
 *
 * Почему отдельный модуль. Аудит устойчивых черт (`filterStableTraits`) держится
 * не на алгоритме, а на словарях: что чертой не является, что чем является
 * синонимом, что чему противоречит, какая формулировка говорит о постоянном
 * свойстве, а какая — о минутном состоянии. Пока словари лежали внутри
 * двухтысячестрочного файла, они были написаны под английский и продублированы
 * по-русски наполовину, и это не читалось как проблема. Мерка показала, чем это
 * было: **ни один из 3098 абзацев «Преступления и наказания» не совпадает с
 * английскими шаблонами прямого авторского утверждения**, тогда как с русскими
 * совпадают 216. То есть на русской книге ветка `direct` не срабатывала никогда,
 * обещание промпта «прямое авторское утверждение — достаточно одного фрагмента»
 * было невыполнимо, а список `DIRECT_ONLY` работал запретом, а не требованием
 * доказательства.
 *
 * Второе, что делает этот модуль. Русское слово в тексте стоит в форме, а
 * словари сравнивались строкой: «добрая» не равно «добрый», поэтому по-русски не
 * работали ни склейка синонимов, ни поиск противоречий, ни запрет внешности —
 * «красивый» отбрасывался, «красивая» проходила. Здесь у концепта есть основа, и
 * сравнение идёт по ней.
 *
 * Английские таблицы сохранены: восемь из десяти замороженных фикстур
 * идентичности англоязычные, и их поведение менять нечем. Таблица выбирается по
 * письменности самого значения, а не по языку книги: карточка одноязычна, и
 * гадать не нужно.
 */

