/**
 * Минимальная длина основы. Двух букв достаточно и меньше нельзя: у коротких
 * русских прилагательных основа именно такая («злой» и «злая» — «зл»), а порог в
 * четыре буквы оставлял их несведёнными и ломал ровно то, ради чего основа
 * считается. Опасности склейки это не создаёт: основы короче четырёх букв
 * сравниваются только на полное равенство (см. traitStemsAgree).
 */
export const MIN_TRAIT_STEM_LENGTH = 2
/** Тот же порог при поиске лексемы в цитате. */
const MIN_LEXEME_STEM_LENGTH = 2

const CYRILLIC_WORD = /^[а-яё-]+$/u

/**
 * Окончания русских прилагательных, причастий и кратких форм — длинные раньше
 * коротких, иначе «доброго» срежется до «добро».
 */
const TRAIT_ENDINGS = Object.freeze([
  'ейшего', 'ейшему', 'ейшими', 'ейшею',
  'ейший', 'ейшая', 'ейшее', 'ейшие', 'ейших', 'ейшим', 'ейшую',
  'ого', 'его', 'ому', 'ему', 'ыми', 'ими',
  'ый', 'ий', 'ой', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие',
  'ым', 'им', 'ых', 'их', 'ую', 'юю', 'ею', 'ей', 'ом', 'ем',
  'а', 'о', 'ы', 'и', 'е', 'я', 'у', 'ю', 'ь', 'й'
])

/**
 * Значение из двух черт, склеенных союзом: «добрый и честный» — это две черты, а
 * не одна, и аудит обязан отказать. Границы слова заданы lookaround'ом по
 * `\p{L}`: `\b` в JavaScript определён по ASCII, и прежний шаблон
 * `/\b(?:and|or|и|или)\b/` русские союзы не ловил вообще — по-английски черта
 * отклонялась, по-русски проходила.
 */
export const CONJOINED_TRAIT_VALUE = /(?<!\p{L})(?:and|or|и|или)(?!\p{L})/iu

/** Нормализованное значение: регистр, ё→е, только буквы и цифры. */
export function normalizedTraitValue(value) {
  return String(value || '')
    .normalize('NFKC')
    .toLocaleLowerCase('ru-RU')
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
    .replace(/\s+/g, ' ')
}

/**
 * Основа русского слова-черты. Латиница не трогается: английские таблицы
 * написаны словарными формами, и стемминг сдвинул бы их поведение.
 */
export function traitStem(word, minimumLength = MIN_TRAIT_STEM_LENGTH) {
  const token = String(word || '')
  if (!CYRILLIC_WORD.test(token)) return token
  for (const ending of TRAIT_ENDINGS) {
    if (!ending || !token.endsWith(ending)) continue
    const stem = token.slice(0, token.length - ending.length)
    if (stem.length >= minimumLength) return stem
  }
  return token
}

/**
 * Ключ концепта: основа каждого слова значения. По этому ключу и только по нему
 * работают синонимы, противоречия и запреты — иначе «добрая» и «добрый» были бы
 * двумя разными чертами одного человека.
 */
export function traitConceptKey(value) {
  const normalized = normalizedTraitValue(value)
  if (!normalized) return ''
  const stemmed = normalized.split(' ').map((token) => traitStem(token)).join(' ')
  // Таблица синонимов берётся из модуля, а не из параметра: функция передаётся
  // в `.map`, а `.map` подставляет вторым аргументом индекс.
  return TRAIT_SYNONYM_KEYS.get(stemmed) ?? TRAIT_SYNONYM_KEYS.get(normalized) ?? stemmed
}

