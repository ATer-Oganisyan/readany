/**
 * Появления шагов онбординга, собранные в одном месте.
 *
 * Онбординг — единственное место в приложении, где движение оправдано щедро:
 * пользователь видит эти экраны один раз в жизни, и цена анимации платится
 * однократно. Но именно поэтому здесь же обязателен учёт системной настройки
 * «уменьшить движение»: это первое, что видит человек, который её включил, и
 * включают её из-за укачивания, а не ради вкуса.
 *
 * `ReduceMotion.System` оставляет проявление и снимает сдвиг с пружиной —
 * «меньше и мягче», а не «ничего»: смена шага по-прежнему объясняется.
 */
import { FadeInDown, ReduceMotion, SlideInRight } from "react-native-reanimated";

/** Верхняя граница для интерфейсного движения; 500 мс ощущались как задержка. */
const PAGE_DURATION_MS = 300;

/** Появление страницы шага целиком. */
export const pageEntrance = () =>
  SlideInRight.duration(PAGE_DURATION_MS).reduceMotion(ReduceMotion.System);

/**
 * Появление отдельной строки внутри шага, каскадом.
 *
 * @param delayMs задержка относительно появления страницы
 */
export const lineEntrance = (delayMs: number) =>
  FadeInDown.delay(delayMs).springify().reduceMotion(ReduceMotion.System);
