/**
 * Единая точка входа для тактильной отдачи.
 *
 * Правила, которым подчинён каждый вызов ниже:
 *
 * 1. Отдача срабатывает в том же кадре, что и визуальное изменение — в момент
 *    причины (защёлка встала), а не по завершении анимации. Отставшая вибрация
 *    читается как сбой, а не как отклик.
 * 2. Одна отдача на одно действие пользователя. Никогда на прокрутку, никогда
 *    на кадр, никогда на появление, которого пользователь не вызывал.
 * 3. Отдача никогда не единственный сигнал. У части пользователей она выключена
 *    системно, на большинстве Android-устройств её нет вовсе — визуал обязан
 *    работать сам по себе.
 *
 * Все функции намеренно синхронные и «выстрелил и забыл»: expo-haptics
 * отклоняет промис на устройствах без поддержки, и это не повод падать.
 */
import * as Haptics from "expo-haptics";

function fire(run: () => Promise<void>) {
  try {
    void run().catch(() => {
      // Устройство без вибромотора или отключённая системная настройка —
      // штатная ситуация, а не ошибка.
    });
  } catch {
    // Нативной части нет в текущей сборке dev-client: модуль добавлен в
    // package.json, но клиент собран до этого. Вызов бросает синхронно, и
    // отсутствие вибрации не должно ронять экран.
  }
}

/** Значение перескочило через шаг: сегмент, ячейка пикера, засечка слайдера. */
export function hapticSelection() {
  fire(() => Haptics.selectionAsync());
}

/** Что-то встало на место: защёлка, притягивание, завершённый перенос. */
export function hapticLight() {
  fire(() => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light));
}

/** Приземлился тяжёлый объект или сработало разрушающее действие. */
export function hapticMedium() {
  fire(() => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Medium));
}

/** Операция завершилась успехом. */
export function hapticSuccess() {
  fire(() => Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success));
}

/** Операция завершилась ошибкой. */
export function hapticError() {
  fire(() => Haptics.notificationAsync(Haptics.NotificationFeedbackType.Error));
}
